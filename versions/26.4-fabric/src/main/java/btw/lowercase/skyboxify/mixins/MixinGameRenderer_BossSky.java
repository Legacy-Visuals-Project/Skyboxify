package btw.lowercase.skyboxify.mixins;

import btw.lowercase.skyboxify.api.SkyboxifyImpl;
import com.llamalad7.mixinextras.injector.wrapmethod.WrapMethod;
import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import net.minecraft.client.renderer.LevelRenderer;
import org.spongepowered.asm.mixin.Mixin;

@Mixin(LevelRenderer.class)
public abstract class MixinGameRenderer_BossSky {
    @WrapMethod(method = "shouldRenderSky")
    private boolean skyboxify$allowSkiesDuringBoss(final Operation<Boolean> original) {
        return original.call() || SkyboxifyImpl.skyboxManager().isEnabled();
    }
}
